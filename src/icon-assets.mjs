export function iconAssetPath(id) {
  return iconAssets[id]?.file;
}

export function iconAssetUrl(id) {
  const file = iconAssetPath(id);
  if (!file) throw new Error(`未登錄的圖標 ID：${id}`);
  return new URL(`../assets/${file}`, import.meta.url);
}
